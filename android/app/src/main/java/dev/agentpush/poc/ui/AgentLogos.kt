internal fun canonicalAgentLogoKey(source: String): String {
    val key = source.trim().lowercase()
    return aliases[key] ?: key
}

@DrawableRes
internal fun agentLogoDrawable(source: String): Int? =
    agentLogoDrawables[canonicalAgentLogoKey(source)]

internal fun hasAgentLogo(source: String): Boolean =
    agentLogoDrawable(source) != null || agentLogoSpec(source) != null

internal fun agentLogoColor(source: String): Color? =
    agentLogoSpec(source)?.parts?.firstOrNull()?.color

internal fun agentFallbackColor(source: String): Color {
    val key = source.trim().lowercase().ifBlank { "agent" }
    var hash = 0
    for (ch in key) {
        hash = hash * 31 + ch.code
    }
    return fallbackPalette[abs(hash) % fallbackPalette.size]
}

internal fun agentFallbackInitials(source: String, label: String = ""): String {
    val cleanLabel = label.trim()
    val raw = cleanLabel.ifBlank { source.trim() }
    if (raw.isBlank()) return "AG"
    val words = raw.split('-', '_', ' ').filter { it.isNotBlank() }
    if (words.size >= 2) {
        return "${words[0].first().uppercaseChar()}${words[1].first().uppercaseChar()}"
    }
    return raw.take(2).uppercase()
}

@Composable
internal fun AgentLogoMark(
    source: String,
    size: Dp,
    modifier: Modifier = Modifier,
) {
    val drawable = remember(source) { agentLogoDrawable(source) }
    if (drawable != null) {
        Image(
            painter = painterResource(drawable),
            contentDescription = null,
            modifier = modifier.size(size),
            contentScale = ContentScale.Fit,
        )
        return
    }
    val spec = remember(source) { agentLogoSpec(source) } ?: return
    val paths = remember(spec) {
        spec.parts.map { part ->
            part.color to PathParser().parsePathString(part.pathData).toPath().apply {
                fillType = if (part.evenOdd) PathFillType.EvenOdd else PathFillType.NonZero
            }
        }
    }
    Canvas(modifier.size(size)) {
        val factor = this.size.minDimension / 24f
        withTransform({
            scale(factor, factor, pivot = Offset.Zero)
        }) {
            paths.forEach { (color, path: Path) ->
                drawPath(path, color)
            }
        }
    }
}
