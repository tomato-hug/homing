internal fun agentLogoSpec(source: String): AgentLogoSpec? {
    val key = source.trim().lowercase()
    return agentLogos[key] ?: aliases[key]?.let(agentLogos::get)
}

internal fun agentLogoColor(source: String): Color? =
    agentLogoSpec(source)?.parts?.firstOrNull()?.color

@Composable
internal fun AgentLogoMark(
    source: String,
    size: Dp,
    modifier: Modifier = Modifier,
) {
    val spec = remember(source) { agentLogoSpec(source) } ?: return
    val paths = remember(spec) {
        spec.parts.map { part ->
            part.color to PathParser().parsePathString(part.pathData).toPath().apply {
                fillType = PathFillType.EvenOdd
            }
        }
    }
    Canvas(modifier.size(size)) {
        val factor = this.size.minDimension / 24f
        withTransform({
            scale(factor, factor, pivot = Offset.Zero)
        }) {
            paths.forEach { (color, path: Path) ->
                drawPath(path, color)
            }
        }
    }
}
